-- bridge/schema.sql
-- Mirrors the Rust types: Status {Pending, Done}, Priority {Low, Medium, High}.
-- CHECK values are capitalized because serde serializes the variant names as-is.

CREATE TABLE tasks (
    id  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description TEXT NOT NULL, 
    status      TEXT NOT NULL DEFAULT 'Pending'
                CHECK (status IN('Pending', 'Done')),
    priority    TEXT NOT NULL DEFAULT 'Medium'
                CHECK (priority IN('Low', 'Medium', 'High'))
);

CREATE TABLE tags (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, 
    name TEXT NOT NULL UNIQUE
);

CREATE TABLE task_tags (
    task_id BIGINT NOT NULL REFERENCES tasks (id) ON DELETE CASCADE,
    tag_id BIGINT NOT NULL REFERENCES tags (id) ON DELETE RESTRICT,
    PRIMARY KEY (task_id, tag_id)
);


-- Serves "all tasks tagged X". The PK's leading column (task_id) already
-- covers task -> tags lookups and FK checks, so no index on task_id.
CREATE INDEX task_tags_tag_id_idx ON task_tags (tag_id);
